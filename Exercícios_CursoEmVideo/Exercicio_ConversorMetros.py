# Crie um programa onde converta metros
# em centimetro e milimetros e mostre
# pro usuário
valorMetro = float(input("Digite o valor do metro: "))
valorCentimetros = valorMetro * 100
valorMilimetros = valorMetro * 1000
print("O valor em metros é igual a: ", valorMetro, " METROS")
print("Convertendo para centimetros: ", valorCentimetros, " CENTIMETROS")
print("Convertendo para milimetros: ", valorMilimetros, " MILIMETROS")